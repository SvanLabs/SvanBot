#[test]
fn the_range_model_matches_v10_on_every_spot() {
    let prof = Profile::population_default();
    let rp = RangeParams::DEFAULT;
    let mut boards = Boards::default();
    let spots = spots();
    assert_eq!(spots.len(), V10.len());
    for (spot, want) in spots.iter().zip(V10) {
        let sit = &spot.situation;
        let ranges = estimate_ranges(sit, &prof, &rp, &mut boards);
        let all: Vec<f32> = ranges.values().flat_map(|r| r.w.iter().copied()).collect();
        let hero = perceived_range(sit, &prof, &rp, &mut boards);
        let to = sit.min_raise_to.unwrap_or(0);
        let aggr = aggressive_likelihood(sit, &prof, to, &rp, &mut boards);
        let first = ranges.values().next().expect("an opponent");
        let (share, cont) = if sit.street == Street::Preflop {
            villain_continue_preflop(first, 0.2, 0.45, 0.6)
        } else {
            let info = boards.info(&sit.board);
            let eq = equity_vs_histogram(&strength_histogram(&hero, &info.strength), sit.street);
            villain_continue(first, &info.strength, &eq, 0.3, 0.6)
        };
        let got = (
            want.0,
            digest(&all),
            digest(&hero.w[..]),
            digest(&aggr),
            share.to_bits(),
            digest(&cont.w[..]),
        );
        assert_eq!(got, want, "spot {}", want.0);
    }
}
