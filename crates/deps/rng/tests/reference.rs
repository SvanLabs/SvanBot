fn sequence() -> Vec<u64> {
    let mut out: Vec<u64> = Vec::new();
    for seed in [0u64, 1, 42, 0xdead_beef, u64::MAX] {
        let mut r = SmallRng::seed_from_u64(seed);
        for _ in 0..3 {
            out.push(r.next_u64());
        }
        for _ in 0..3 {
            out.push(r.next_u32() as u64);
        }
        for _ in 0..3 {
            out.push(r.random::<f64>().to_bits());
        }
        for _ in 0..3 {
            out.push(r.random::<f32>().to_bits() as u64);
        }
        for _ in 0..3 {
            out.push(r.random::<bool>() as u64);
        }
        for _ in 0..3 {
            out.push(r.random::<u64>());
        }
        for _ in 0..6 {
            out.push(r.random_range(0..52u8) as u64);
        }
        for i in [0usize, 1, 5, 100, 3_000_000] {
            out.push(r.random_range(0..=i) as u64);
        }
        for k in [0usize, 3, 7] {
            out.push(r.random_range(k..40) as u64);
        }
        for _ in 0..3 {
            out.push(r.random_range(1..=5_000i64) as u64);
        }
        for _ in 0..3 {
            out.push(r.random_range(-100..=20_000i32) as i64 as u64);
        }
        for _ in 0..2 {
            out.push(r.random_range(5_000..=200_000i64) as u64);
        }
        for _ in 0..2 {
            out.push(r.random_range(0..1000u64));
        }
        out.push(r.random_range(0..(u32::MAX as usize + 7)) as u64);
        for p in [0.0, 0.3, 0.999, 1.0] {
            out.push(r.random_bool(p) as u64);
        }
        for n in [0usize, 1, 2, 6, 17] {
            let mut v: Vec<u64> = (0..n as u64).collect();
            v.shuffle(&mut r);
            out.extend(v);
        }
        out.push(r.next_u64());
    }
    out
}

#[test]
fn matches_rand_0_10_bit_for_bit() {
    let got = sequence();
    assert_eq!(got.len(), REFERENCE.len());
    for (i, (g, e)) in got.iter().zip(REFERENCE).enumerate() {
        assert_eq!(g, e, "value {i} differs");
    }
}
