// The README's headline (V11-20): the Arena run pinned in `fleet/headline.json`, the block of the
// README that says its number, and the check that the two still agree.
//   bun tools/headline.ts           checks README.md against the pinned run; exits 1 on a drift
//   bun tools/headline.ts --print   writes the block the pinned run says, and no more
//   bun tools/headline.ts --pin A    reads the newest run in `arena.json` file A, writes it to
//                                   `fleet/headline.json`, and writes its block into the README
//
// The run the headline names is pinned, not read from `arena.json` as whatever came last: CI plays
// the Arena on a pull request before it merges, and a README that followed it would say numbers
// the branch never saw, from a commit that was never merged. So `bun tools/headline.ts --pin` is
// run once, on the base branch, over the run CI left in a pull request's artifact: the headline
// moves when the operator moves it, and the check that runs in CI can always be satisfied by an
// author who pinned the run the branch actually plays.
//
// A run is named by what plays it again — commit, champion and seed — so a reader can hold the
// headline's number to the file it was played from. The block names its run, keeps every
// opponent's line, and says what it is not: heads up against the sparring archetypes and the
// pricer is the league so far, not the full benchmark.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export type Row = { opponent: string; deals: number; mbb_per_100: number; ci95: number };
export type Run = { commit: string; champion: string; seed: number; rows: Row[] };

type Aggregate = { deals: number; mbb_per_100: number; ci95: number | undefined };
// Always the same shape with `problems` there to be read: a caller that has to narrow a union
// learns the rules of TypeScript instead of the rules of the headline.
export type Headline = { block: string; aggregate: Aggregate; problems: string[] };

export const OPEN = "<!-- headline -->";
export const CLOSE = "<!-- /headline -->";

const NO_PIN = "no Arena run is pinned in fleet/headline.json: the headline has nothing to say";
const NO_ROWS = "the pinned Arena run played no deals: the headline has nothing to say";
const NO_DEALS = "the pinned Arena run's deals add to none: the headline has nothing to say";

const SOURCE = [
  "<!-- Generated by tools/headline.ts from fleet/headline.json. Do not edit by hand: pin a",
  "     run, or change the tool. -->",
];
const NOT =
  "This is the league so far: heads up against the sparring archetypes and the pricer, not";

/** The block: a number over the whole league, the run it came from, and the lines behind it. */
export function headline(run: Run | undefined): Headline {
  // No pin is no headline, and the check refuses it: a branch that deleted the pin would else
  // pass with a README saying nothing, which is the hand-typing this ticket exists to prevent.
  if (!run) {
    return {
      block: "",
      aggregate: { deals: 0, mbb_per_100: 0, ci95: undefined },
      problems: [NO_PIN],
    };
  }
  const none = (problem: string): Headline => ({
    block: "",
    aggregate: { deals: 0, mbb_per_100: 0, ci95: undefined },
    problems: [problem],
  });
  if (run.rows.length === 0) return none(NO_ROWS);
  const deals = run.rows.reduce((sum, row) => sum + row.deals, 0);
  if (deals === 0) return none(NO_DEALS);

  // The league's rate is what it won over the hands it played, so a bout weighs by its deals.
  const mbb_per_100 = run.rows.reduce((sum, row) => sum + row.mbb_per_100 * row.deals, 0) / deals;
  // Its interval pools the rows the way a pooled mean does: a row's half-width is 1.96 standard
  // errors over its deals, so Var(pooled mean) = Σ (n_i/N)² · (ci_i/1.96)²/n_i. A row that
  // measured no interval measured nothing at all, and cannot be taken as an exact zero: the
  // pool's interval is then unmeasured too, rather than narrow on a row's silence.
  const measured = run.rows.every((row) => row.ci95 > 0);
  const variance = measured
    ? run.rows.reduce((sum, row) => {
        const weight = row.deals / deals;
        return sum + (weight * weight * (row.ci95 / 1.96) ** 2) / row.deals;
      }, 0)
    : undefined;
  const ci95 = variance === undefined ? undefined : 1.96 * Math.sqrt(variance);
  const opponents = run.rows.length;
  const league = `over ${count(deals)} deals of the Arena across ${
    opponents === 1 ? "one opponent" : `${count(opponents)} opponents`
  }`;
  const spread = ci95 === undefined ? "95% CI not measured" : `95% CI ±${grouped(ci95)}`;

  // The number is only a number when the interval leaves zero on one side or the other; a sample
  // that straddles it says so, and how wide the interval came out, rather than claiming a rate it
  // cannot support. Below zero is a rate like any other, and a losing one is still the truth.
  const clearOfZero = ci95 !== undefined && Math.abs(mbb_per_100) > ci95;
  const headlineLine = clearOfZero
    ? `**${signed(mbb_per_100)} mbb/100**, ${league}, ${spread}.`
    : `**Not yet distinguishable from zero**: ${signed(mbb_per_100)} mbb/100 ${league}, ${spread}.`;

  const lines = run.rows.map(
    (row) =>
      `| ${row.opponent} | ${signed(row.mbb_per_100)} | ${interval(row.ci95)} | ${count(row.deals)} |`,
  );
  const block =
    [
      OPEN,
      ...SOURCE,
      headlineLine,
      "",
      `Played at commit \`${run.commit}\`, champion \`${run.champion}\`, seed ${run.seed}:`,
      "",
      "| opponent | mbb/100 | 95% CI | deals |",
      "| --- | ---: | ---: | ---: |",
      ...lines,
      "",
      `${NOT} the full benchmark. The run above replays every line.`,
      CLOSE,
    ].join("\n") + "\n";
  return { block, aggregate: { deals, mbb_per_100, ci95 }, problems: [] };
}

/** The block the README holds, markers included, so writing it back is a plain replacement. */
export function between(text: string): { text: string } | { problems: string[] } {
  const open = text.indexOf(OPEN);
  const close = text.indexOf(CLOSE);
  if (open < 0 || close < 0 || close < open) {
    return { problems: ["README.md has no headline markers"] };
  }
  // The block runs to the end of the marker's line, so a README that holds it is exactly the
  // text of one write, wherever the markers sit.
  const line = text.indexOf("\n", close);
  return { text: text.slice(open, line < 0 ? text.length : line + 1) };
}

/** Whether the README's block is the pinned run's. Empty means it is. */
export function problems(run: Run | undefined, readme: string): string[] {
  const said = headline(run);
  if (said.problems.length > 0) return said.problems;
  const held = between(readme);
  if ("problems" in held) return held.problems;
  return held.text === said.block ? [] : ["README.md's headline is not the pinned run's"];
}

/** The README with its block replaced by `block`, or the README and the reason it cannot be. */
export function replace(readme: string, block: string): { text: string } | { problems: string[] } {
  const held = between(readme);
  if ("problems" in held) return held;
  const at = readme.indexOf(held.text);
  return { text: readme.slice(0, at) + block + readme.slice(at + held.text.length) };
}

/** A number as the block says it: signed, to three significant figures from 100 mbb up. */
function signed(value: number): string {
  return (value < 0 ? "-" : "+") + grouped(Math.abs(value));
}

function interval(value: number): string {
  // An interval of exactly zero is a mean that was not measured, not one measured exactly.
  return value === 0 ? "not measured" : `±${grouped(value)}`;
}

/** Three significant figures: the sample cannot say more, and padding it would pretend it can. */
function grouped(value: number): string {
  if (!Number.isFinite(value)) return "…";
  if (value === 0) return "0.00";
  const digits = Math.max(0, 2 - Math.floor(Math.log10(Math.abs(value))));
  const text = value.toFixed(digits);
  // Group the whole part only: a thousands separator inside a fraction would be a wrong number.
  if (Math.abs(value) < 1000) return text;
  const point = text.indexOf(".");
  const whole = point < 0 ? text : text.slice(0, point);
  const fraction = point < 0 ? "" : text.slice(point);
  return whole.replace(/\B(?=(\d{3})+(?!\d))/g, ",") + fraction;
}

function count(value: number): string {
  return String(value).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
}

if (import.meta.main) {
  const root = join(import.meta.dir, "..");
  // The pin is a file of the repository, and always the clone's: it is what the check reads and
  // what a commit carries, so it cannot follow the box's `SVANBOT_FLEET` to a fleet directory
  // outside the tree. The source run is whatever path is named, the downloaded artifact included.
  const pinPath = join(root, "fleet", "headline.json");
  const readmePath = join(root, "README.md");
  const args = process.argv.slice(2);
  const readPin = (): Run | undefined =>
    existsSync(pinPath) ? JSON.parse(readFileSync(pinPath, "utf8")) : undefined;
  const readReadme = (): string => (existsSync(readmePath) ? readFileSync(readmePath, "utf8") : "");

  const pinAt = args.indexOf("--pin");
  if (pinAt >= 0) {
    // The pinned run is a run `arena.json` holds, and nothing else: the tool writes the same
    // text back, so the pin can be read as a line of the file it came from.
    const source = args[pinAt + 1] ?? "";
    const text = existsSync(source) ? readFileSync(source, "utf8") : "";
    const run = (JSON.parse(text || "{}").runs ?? [])[0] as Run | undefined;
    const said = headline(run);
    if (said.problems.length > 0) {
      console.log(said.problems.join("\n"));
      process.exit(1);
    }
    const written = replace(readReadme(), said.block);
    if ("problems" in written) {
      console.log(written.problems.join("\n"));
      process.exit(1);
    }
    mkdirSync(join(root, "fleet"), { recursive: true });
    writeFileSync(pinPath, `${JSON.stringify(run)}\n`);
    writeFileSync(readmePath, written.text);
    console.log(`pinned ${run?.commit} and wrote its headline`);
    process.exit(0);
  }

  if (args.includes("--print")) {
    const said = headline(readPin());
    if (said.problems.length > 0) {
      console.log(said.problems.join("\n"));
      process.exit(1);
    }
    console.log(said.block);
    process.exit(0);
  }

  const found = problems(readPin(), readReadme());
  for (const problem of found) console.log(problem);
  process.exit(found.length > 0 ? 1 : 0);
}
